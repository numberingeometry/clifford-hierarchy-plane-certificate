"""Fact (C17): Sylow cosets in S_6 and three-element subsets. Exact recomputation.

The graph and its maximal cliques are generated from all of S_6; no list of cliques or earlier output is
read. Internal key: C17.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
from itertools import combinations, permutations
import json
from pathlib import Path
import time


EXPECTED_CLIQUE_HISTOGRAM = {7: 180, 15: 45}
EXPECTED_DEFICIENT_SUBSETS = 12240
EXPECTED_BAD_TRIPLES = 1440


def need(condition, message):
    if not condition:
        raise ValueError(message)


def bits(mask):
    while mask:
        bit = mask & -mask
        yield bit.bit_length() - 1
        mask ^= bit


def maximal_cliques(adjacency):
    """Enumerate every maximal clique by the exhaustive Bron-Kerbosch invariant.

    R is a clique; P and X partition the unprocessed and processed vertices
    adjacent to every R vertex. Each maximal extension intersects P minus
    the pivot's neighbors. Moving each visited vertex from P to X prevents
    duplication while retaining every extension in exactly one branch.
    """
    n = len(adjacency)
    domain = (1 << n) - 1
    for vertex, neighbors in enumerate(adjacency):
        need(type(neighbors) is int and 0 <= neighbors <= domain,
             "graph neighbor mask exceeds its finite domain")
        need(not (neighbors >> vertex & 1), "graph has a self edge")
        need(all(adjacency[other] >> vertex & 1 for other in bits(neighbors)),
             "graph is not undirected")
    cliques = []
    nodes = 0

    def bk(R, P, X):
        nonlocal nodes
        nodes += 1
        need(not P & X and not R & (P | X), "Bron-Kerbosch partition invariant")
        if not P and not X:
            cliques.append(R)
            return
        pivot = max(bits(P | X), key=lambda vertex: (adjacency[vertex] & P).bit_count())
        candidates = P & ~adjacency[pivot]
        for vertex in bits(candidates):
            bit = 1 << vertex
            bk(R | bit, P & adjacency[vertex], X & adjacency[vertex])
            P &= ~bit
            X |= bit

    bk(0, domain, 0)
    need(len(cliques) == len(set(cliques)), "duplicate maximal clique")
    for clique in cliques:
        vertices = list(bits(clique))
        need(all(clique & ~(adjacency[v] | (1 << v)) == 0 for v in vertices),
             "enumerated set is not a clique")
        extension = domain
        for vertex in vertices:
            extension &= adjacency[vertex]
        need(extension == 0, "enumerated clique is not maximal")
    return sorted(cliques), nodes


def validate_summary(record):
    """Unconditional release invariants, also used by rejection controls."""
    need(record.get("permutations") == 720 and record.get("sylows") == 45
         and record.get("base_sylow_order") == 16
         and record.get("two_elements") == 256 and record.get("graph_vertices") == 255,
         "S6/Sylow/vertex domains changed")
    need(record.get("maximal_cliques") == 225
         and record.get("maximal_clique_histogram") == EXPECTED_CLIQUE_HISTOGRAM,
         "complete maximal-clique histogram changed")
    need(record.get("common_sylow_cliques") == 45
         and record.get("deficient_maximal_cliques") == 180,
         "common-Sylow maximal-clique partition changed")
    need(record.get("deficient_subsets_checked") == EXPECTED_DEFICIENT_SUBSETS,
         "complete deficient-subset domain changed")
    need(record.get("distinct_bad_triples") == EXPECTED_BAD_TRIPLES,
         "bad-triple domain changed")
    need(record.get("unresolved_deficient_subsets") == 0,
         "a deficient subset has no verified bad triple")


def validate_bad_triple(triple, quotient_masks, candidate):
    need(len(triple) == 3 and len(set(triple)) == 3
         and all(vertex in candidate for vertex in triple), "bad triple is not in its candidate set")
    a, b, c = triple
    need(not (quotient_masks[a][b] & quotient_masks[a][c]),
         "purported bad triple lies in a Sylow right coset")


def run():
    started = time.perf_counter()
    all_perms = list(permutations(range(6)))
    identity = tuple(range(6))

    def comp(a, b):
        return tuple(a[b[j]] for j in range(6))

    def inv(a):
        return tuple(a.index(j) for j in range(6))

    # The same subgroup is generated by four transpositions.
    edge = frozenset((4, 5))
    matching = {frozenset((0, 1)), frozenset((2, 3))}
    base = frozenset(g for g in all_perms if frozenset(g[j] for j in edge) == edge
                     and {frozenset(g[j] for j in pair) for pair in matching} == matching)
    need(len(all_perms) == len(set(all_perms)) == 720, "complete S6 domain")
    need(len(base) == 16 and identity in base
         and all(comp(a, b) in base for a in base for b in base), "base Sylow subgroup")
    sylows = set()
    for g in all_perms:
        inverse = inv(g)
        sylows.add(frozenset(comp(comp(g, h), inverse) for h in base))
    sylows = sorted(sylows, key=lambda subgroup: sorted(subgroup))
    need(len(sylows) == 45 and all(len(subgroup) == 16 for subgroup in sylows),
         "complete conjugate Sylow cover")
    masks = {g: sum(1 << j for j, subgroup in enumerate(sylows) if g in subgroup)
             for g in all_perms}
    two = sorted(g for g in all_perms if masks[g])
    need(len(two) == 256 and two[0] == identity, "two-element domain with identity")
    for g in all_perms:
        square = comp(g, g)
        need(bool(masks[g]) == (comp(square, square) == identity), "complete two-element cover")
    membership = [masks[g] for g in two]
    vertices = two[1:]
    adjacency = [sum(1 << j for j, other in enumerate(vertices)
                     if i != j and masks[g] & masks[other]) for i, g in enumerate(vertices)]
    cliques, bk_nodes = maximal_cliques(adjacency)
    histogram = dict(sorted(Counter(clique.bit_count() for clique in cliques).items()))
    need(histogram == EXPECTED_CLIQUE_HISTOGRAM, "complete recomputed maximal-clique histogram")

    def shared(indices):
        common = (1 << len(sylows)) - 1
        for vertex in indices:
            common &= membership[vertex]
        return common

    # Exact right-coset criterion for {a,b,c}: b a^-1 and c a^-1
    # generate a two-group iff they lie together in one enumerated Sylow.
    inverses = [inv(g) for g in two]
    quotient_masks = [[masks[comp(g, inverse)] for g in two] for inverse in inverses]
    common_cliques = deficient_cliques = tested = unresolved = 0
    deficient_sets, bad_triples = set(), set()
    witness_bindings = []
    verified_triples = 0
    for clique in cliques:
        members = tuple(vertex + 1 for vertex in bits(clique))
        if shared(members):
            need(len(members) == 15, "common-Sylow maximal clique must have fifteen vertices")
            common_cliques += 1
            continue
        need(len(members) == 7, "deficient maximal clique must have seven vertices")
        deficient_cliques += 1
        for size in range(2, len(members) + 1):
            for subset in combinations(members, size):
                if shared(subset):
                    continue
                tested += 1
                deficient_sets.add(subset)
                candidate = (0,) + subset
                found = []
                for triple in combinations(candidate, 3):
                    a, b, c = triple
                    verified_triples += 1
                    if quotient_masks[a][b] & quotient_masks[a][c]:
                        continue
                    validate_bad_triple(triple, quotient_masks, candidate)
                    found.append(triple)
                    bad_triples.add(triple)
                if not found:
                    unresolved += 1
                    raise ValueError("deficient subset without a verified bad triple: " + str(candidate))
                witness_bindings.append({"subset": list(subset), "bad_triple": list(found[0])})
    record = {"status": "PASS", "route": "recompute", "exact": True,
              "fact": "s6-sylow-cosets-and-three-element-subsets",
              "permutations": 720, "base_sylow_order": 16, "sylows": len(sylows),
              "two_elements": len(two), "graph_vertices": len(vertices),
              "maximal_cliques": len(cliques), "maximal_clique_histogram": histogram,
              "common_sylow_cliques": common_cliques,
              "deficient_maximal_cliques": deficient_cliques,
              "deficient_subsets_checked": tested, "distinct_deficient_subsets": len(deficient_sets),
              "distinct_bad_triples": len(bad_triples),
              "unresolved_deficient_subsets": unresolved, "actual_triples_tested": verified_triples,
              "bron_kerbosch_search_nodes": bk_nodes,
              "complete_clique_enumeration": "pivoted Bron-Kerbosch from the entire 255-vertex graph",
              "cliques": [[vertex + 1 for vertex in bits(clique)] for clique in cliques],
              "two_element_permutations": [list(g) for g in two],
              "deficient_subset_witnesses": witness_bindings,
              "bad_triples": [list(triple) for triple in sorted(bad_triples)],
              "normalization": "right translate F by an element inverse; identity index zero",
              "coset_test": "b a^-1 and c a^-1 in one Sylow subgroup",
              "arithmetic": "exact permutations and integer Sylow-membership masks",
              "independent_kernel": False,
              "checker_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "seconds": time.perf_counter() - started}
    validate_summary(record)
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write a new execution record")
    args = parser.parse_args()
    record = run()
    encoded = json.dumps(record, indent=2) + "\n"
    if args.output is not None:
        with args.output.open("x", encoding="utf-8") as stream:
            stream.write(encoded)
    print(encoded, end="")


if __name__ == "__main__":
    main()
